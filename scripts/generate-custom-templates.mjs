import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Enumerate the custom-template "kits" this build knows about.
 *
 * A kit is a self-contained coded page: a folder under `inertia/custom/kits/`
 * holding a `kit.json` marker plus an `index.tsx` entry (see that folder's
 * README). It is the folder counterpart to a single-file code page under
 * `inertia/custom/pages/`, and the operator payload a future template
 * marketplace installs.
 *
 * This mirrors `generate-code-pages.mjs` exactly, and for the same two reasons:
 *
 *  1. **Server validation.** The browser finds kits through `import.meta.glob`,
 *     which Vite expands at build time; the server cannot `readdir` the `.tsx`
 *     sources because `node ace build` ships compiled code, not sources. This
 *     generated manifest lets `PagesService.assertComponent` reject a page whose
 *     `component` names a kit that does not exist, and feeds the admin/MCP
 *     picker so it only ever offers real kits.
 *
 *  2. **Tailwind.** A real (installed) kit lives in a gitignored folder, and
 *     Tailwind v4 skips gitignored paths unless a path names the directory
 *     explicitly — the same `pl-12`-vanishes failure `generate-module-sources`
 *     exists to prevent. So one `@source` line per kit is emitted too.
 *
 * Two committed, sorted, write-on-change artifacts:
 *   app/services/custom_templates.generated.ts   the manifest (under `#services/*`)
 *   inertia/css/custom-templates.generated.css    the Tailwind `@source` lines
 */

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const kitsDir = join(root, 'inertia/custom/kits')
const tsOut = join(root, 'app/services/custom_templates.generated.ts')
const cssOut = join(root, 'inertia/css/custom-templates.generated.css')

/** A kit = a directory holding `kit.json`; `.`/`_`-prefixed folders are skipped. */
function kitFolders() {
  try {
    return readdirSync(kitsDir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .filter((name) => !name.startsWith('.') && !name.startsWith('_'))
      .filter((name) => existsSync(join(kitsDir, name, 'kit.json')))
      .sort()
  } catch {
    return []
  }
}

/** Read `{ name, description }` from a kit's marker, tolerating a bad/missing file. */
function readMeta(id) {
  try {
    const raw = JSON.parse(readFileSync(join(kitsDir, id, 'kit.json'), 'utf8'))
    const name = typeof raw?.name === 'string' && raw.name.trim() ? raw.name.trim() : id
    const description = typeof raw?.description === 'string' ? raw.description.trim() : ''
    return { id, name, description }
  } catch {
    return { id, name: id, description: '' }
  }
}

const kits = kitFolders().map(readMeta)

const tsBody = [
  '/* Generated by scripts/generate-custom-templates.mjs — do not edit. */',
  '',
  '/**',
  ' * Every custom-template kit under `inertia/custom/kits/` (a folder with a',
  ' * `kit.json` marker + `index.tsx` entry).',
  ' *',
  ' * Read by `PagesService` to reject a CODE page whose `kit:<id>` component does',
  ' * not exist, and served to the admin / MCP page-create pickers so they only',
  ' * ever offer real kits. `id` is the folder name and the value stored as',
  ' * `page.component = "kit:<id>"`.',
  ' */',
  'export interface CustomTemplate {',
  '  id: string',
  '  name: string',
  '  description: string',
  '}',
  '',
  `export const CUSTOM_TEMPLATES: readonly CustomTemplate[] = ${JSON.stringify(kits, null, 2)}`,
  '',
].join('\n')

const cssBody = [
  '/* Generated by scripts/generate-custom-templates.mjs — do not edit. */',
  '/*',
  ' * One line per custom-template kit, naming each directory explicitly so',
  ' * Tailwind scans it: installed kits are gitignored operator payloads, and',
  ' * Tailwind skips gitignored paths for a directory source or a broad glob but',
  ' * honours a path that names the directory itself.',
  ' */',
  ...kits.map((kit) => `@source "../custom/kits/${kit.id}";`),
  '',
].join('\n')

function writeIfChanged(file, body, label) {
  const current = existsSync(file) ? readFileSync(file, 'utf8') : null
  if (current === body) return false
  writeFileSync(file, body)
  return true
}

const changed = [writeIfChanged(tsOut, tsBody), writeIfChanged(cssOut, cssBody)].some(Boolean)
const summary = kits.map((k) => k.id).join(', ') || 'none'
console.log(
  changed
    ? `[custom-templates] wrote ${kits.length} kit(s): ${summary}`
    : `[custom-templates] up to date (${kits.length} kit(s))`
)
