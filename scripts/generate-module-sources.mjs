import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * Write one `@source` line per module, so Tailwind can see module front-ends.
 *
 * ## Why this cannot just be `@source "../../modules"`
 *
 * Tailwind v4 skips gitignored files, and it applies that rule to a directory
 * source and to a broad glob alike — `@source "../../modules"` and
 * `@source "../../modules/**\/*.tsx"` both silently miss anything `.gitignore`
 * excludes. A path that names the ignored directory **explicitly** is honoured.
 * (Verified against @tailwindcss/node 4.3.0.)
 *
 * That distinction decides whether the marketplace works at all. An installed
 * package lands in `modules/<name>/`, which `.gitignore` excludes by design —
 * operator payloads do not belong in this repository. Without this file, every
 * such package would rebuild successfully and render its admin pages unstyled.
 *
 * ## Why the failure is worth this much machinery
 *
 * It is invisible. A module's UI keeps almost all of its styling, because it
 * reuses the same class vocabulary as `inertia/`; only classes that no other
 * file in the project happens to use go missing. That is how `pl-12` vanished
 * from the money input and left the currency symbol sitting underneath the
 * value — one utility, one component, no error anywhere.
 *
 * The output is committed so a fresh checkout builds before any script has run,
 * and it is sorted and written only when it changes, so it does not churn.
 */

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const modulesDir = join(root, 'modules')
const outFile = join(root, 'inertia/css/modules.generated.css')

/**
 * The same shape rule as `modules/paths.ts` — a directory holding `module.ts`
 * (dev) or `module.js` (build) is a module. Restated here rather than imported
 * because this runs as plain Node before any TypeScript is available.
 */
function moduleFolders() {
  try {
    return readdirSync(modulesDir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .filter((name) => !name.startsWith('.') && !name.startsWith('_'))
      .filter((name) =>
        ['module.js', 'module.ts'].some((file) => existsSync(join(modulesDir, name, file)))
      )
      .sort()
  } catch {
    return []
  }
}

const names = moduleFolders()

const body = [
  '/* Generated by scripts/generate-module-sources.mjs — do not edit. */',
  '/*',
  ' * One line per module, naming each directory explicitly: Tailwind skips',
  ' * gitignored paths for a directory source or a broad glob, but honours a path',
  ' * that names the directory itself. Installed marketplace packages are',
  ' * gitignored by design, so this is what keeps their UI styled.',
  ' */',
  ...names.map((name) => `@source "../../modules/${name}";`),
  '',
].join('\n')

const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : null

if (current === body) {
  console.log(`[module-sources] up to date (${names.length} module(s))`)
} else {
  writeFileSync(outFile, body)
  console.log(`[module-sources] wrote ${names.length} source(s): ${names.join(', ') || 'none'}`)
}
