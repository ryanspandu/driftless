import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * List the hand-written page components, for the server to validate against.
 *
 * The browser finds these through `import.meta.glob`, which Vite expands at
 * build time. The **server** cannot: `inertia/custom/pages/*.tsx` are sources,
 * and `node ace build` emits compiled server code plus hashed client assets —
 * the `.tsx` files are not in the production image, so a runtime `readdir`
 * would find nothing there while working perfectly in dev.
 *
 * Without this list the only validation possible is client-side, and a page row
 * naming a component that does not exist could still be written through the
 * API. That failure is already live elsewhere in this repo (two announcements
 * controllers render `plugins/announcements/*`, which no longer resolves), and
 * it surfaces as a blank screen rather than an error. Generating the list makes
 * a bad `component` value **unsaveable** instead.
 *
 * Committed, sorted, and written only on change — same contract as
 * `generate-module-sources.mjs`, which this mirrors, including the `.generated.`
 * filename convention. It lands under `app/services/` so the existing
 * `#services/*` import alias covers it without inventing a new one.
 */

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pagesDir = join(root, 'inertia/custom/pages')
const outFile = join(root, 'app/services/code_pages.generated.ts')

function codePageSlugs() {
  try {
    return readdirSync(pagesDir, { withFileTypes: true })
      .filter((entry) => entry.isFile() && entry.name.endsWith('.tsx'))
      .map((entry) => entry.name.replace(/\.tsx$/, ''))
      .filter((name) => !name.startsWith('.') && !name.startsWith('_'))
      .sort()
  } catch {
    return []
  }
}

const slugs = codePageSlugs()

const body = [
  '/* Generated by scripts/generate-code-pages.mjs — do not edit. */',
  '',
  '/**',
  ' * Every hand-written page component under `inertia/custom/pages/`.',
  ' *',
  ' * Read by `PagesService` to reject a CODE page whose component does not',
  ' * exist, and served to the admin page-create dialog so the picker only ever',
  ' * offers real files.',
  ' */',
  `export const CODE_PAGES: readonly string[] = [${slugs.map((s) => `'${s}'`).join(', ')}]`,
  '',
].join('\n')

const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : null

if (current === body) {
  console.log(`[code-pages] up to date (${slugs.length} page(s))`)
} else {
  writeFileSync(outFile, body)
  console.log(`[code-pages] wrote ${slugs.length} page(s): ${slugs.join(', ') || 'none'}`)
}
