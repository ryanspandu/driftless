const KNOWN = new Set(COUNTRY_CODES)

/**
 * Whether a string names a country we recognise.
 *
 * Case-insensitive going in because operators type lowercase; the stored form
 * is always upper — see `normaliseCountry`.
 */
export function isKnownCountry(code: string | null | undefined): boolean {
  if (!code) return false
  return KNOWN.has(code.trim().toUpperCase())
}

/**
 * The storage form of a country code, or `null` if we do not recognise it.
 *
 * Returning `null` rather than passing the input through is the whole point: an
 * unrecognised code must never reach the database, because shipping zones match
 * on exact string equality — a typo would quote no rate at all, silently, and
 * look like a configuration problem rather than a bad address.
 */
export function normaliseCountry(code: string | null | undefined): string | null {
  if (!code) return null
  const upper = code.trim().toUpperCase()
  return KNOWN.has(upper) ? upper : null
}
